function woFindGraphDiv(preferredId, positionIndex) {
  var el = document.getElementById(preferredId);
  if (el && el.data) return el;

  var all = Array.prototype.slice.call(document.querySelectorAll('.js-plotly-plot'));
  var byId = all.find(function (e) { return e.id && e.id.indexOf(preferredId) !== -1; });
  if (byId) return byId;

  if (all.length > positionIndex) return all[positionIndex];
  return null;
}

function woEaseInOutCubic(t) {
  return t < 0.5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2;
}

function woTweenPie(el, fromVals, target, duration) {
  if (!el || !target) return;
  var start = null;

  function step(ts) {
    if (start === null) start = ts;
    var t = Math.min((ts - start) / duration, 1);
    var eased = woEaseInOutCubic(t);
    var vals = target.values.map(function (v, i) {
      var f = fromVals[i] !== undefined ? fromVals[i] : 0;
      return f + (v - f) * eased;
    });
    var total = vals.reduce(function (a, b) { return a + b; }, 0);
    var text = vals.map(function (v) {
      var pct = total > 0 ? Math.round((v / total) * 100) : 0;
      return '<b>' + pct + '%</b>';
    });
    var hovertext = vals.map(function (v, i) {
      return target.labels[i] + ': ' + Math.round(v) + ' workouts';
    });

    Plotly.restyle(el, { values: [vals], text: [text], hovertext: [hovertext] }, [0]);

    if (t < 1) {
      requestAnimationFrame(step);
    } else {
      Plotly.restyle(el, {
        values: [target.values], text: [target.text], hovertext: [target.hovertext]
      }, [0]);
    }
  }
  requestAnimationFrame(step);
}

function woUpdatePie(el, dataset, idx) {
  var target = dataset[idx];
  if (!el || !target) return;
  var fromVals = (el.data && el.data[0] && el.data[0].values) ?
    el.data[0].values.slice() : target.values.map(function () { return 0; });
  Plotly.relayout(el, { annotations: target.annotations });
  woTweenPie(el, fromVals, target, 500);
}

window.addEventListener('load', function () {
  try {
    var activityEl = woFindGraphDiv('activity-pie', 0);
    var distanceEl = woFindGraphDiv('distance-pie', 1);

    if (activityEl) {
      activityEl.on('plotly_buttonclicked', function (data) {
        woUpdatePie(activityEl, window.woActivityPieData, data.active);
      });
    }
    if (distanceEl) {
      distanceEl.on('plotly_buttonclicked', function (data) {
        woUpdatePie(distanceEl, window.woDistancePieData, data.active);
      });
    }
  } catch (err) {
    console.error('Workout pie filter setup failed:', err);
  }
});

